#!/usr/bin/env node
// Writes public/genre-names.js: the other names for every genre and style (TAG_ALIASES in
// lib/config.js, and the translations in lib/genre-words.js), as data for the browser's
// genre suggestions (public/suggest.js). The browser can't load lib/, so this is the copy.
// `npm test` checks the file is up to date. Run: node scripts/gen-genre-names.js
const fs = require('fs');
const path = require('path');
const { GENRES, STYLES, TAG_ALIASES } = require('../lib/config');
const { GENRE_WORDS } = require('../lib/genre-words');

const FILE = path.join(__dirname, '..', 'public', 'genre-names.js');

function build() {
  const out = {};
  const add = (key, a, t) => {
    const aliases = [...new Set(a.map((x) => String(x).replace(/\+/g, ' ').trim()).filter(Boolean))];
    const trans = [...new Set(t.map((x) => String(x).trim()).filter((x) => x && x.length <= 40))];
    if (aliases.length || trans.length) out[key] = { ...(aliases.length ? { a: aliases } : {}), ...(trans.length ? { t: trans } : {}) };
  };
  const words = (tag) => Object.values(GENRE_WORDS[tag] || {}).flat();
  for (const id of Object.keys(GENRES)) add(id, [], [...words(id), ...words(GENRES[id].tags[0])]);
  for (const [main, styles] of Object.entries(STYLES)) {
    void main;
    for (const st of styles) add(`tag:${st}`, TAG_ALIASES[st] || [], words(st));
  }
  return out;
}

function render() {
  return `// GENERATED by scripts/gen-genre-names.js from lib/config.js (TAG_ALIASES) and lib/genre-words.js. Do not edit by hand.\n// Other names for each genre key, for the WRONG GENRE? suggestions: a = aliases, t = translations.\nwindow.GENRE_NAMES = ${JSON.stringify(build())};\n`;
}

if (require.main === module) { fs.writeFileSync(FILE, render()); console.log(`Wrote ${FILE} (${render().length} bytes)`); }
module.exports = { build, render, FILE };
